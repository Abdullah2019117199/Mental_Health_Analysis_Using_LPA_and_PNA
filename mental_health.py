# 3. ORIGINAL STRENGTH
original_strength = estimate_strength(df_analysis)

# 4. CASE-DROPPING BOOTSTRAP
percentages = [0.95, 0.90, 0.80, 0.70, 0.50, 0.25] # Percentage of sample kept
n_iterations = 10 # For Q1 paper, use at least 100-500. Using 10 here for speed.
stability_results = []

print("Starting Stability Bootstrap...")
for p in percentages:
    correlations = []
    n_subsample = int(len(df_mnl) * p)

    for i in range(n_iterations):
        # Randomly sample cases
        subsample = df_analysis.sample(n=n_subsample, replace=False)
        try:
            sub_strength = estimate_strength(subsample)
            # Calculate Spearman correlation between original and subsample rankings
            corr, _ = spearmanr(original_strength, sub_strength)
            correlations.append(corr)
        except:
            continue

    stability_results.append({'proportion_kept': p, 'mean_corr': np.mean(correlations)})

# 5. CALCULATE CS-COEFFICIENT
# The CS-coefficient is the maximum proportion of cases that can be dropped
# while maintaining a correlation of > 0.7 with the original sample.
stability_df = pd.DataFrame(stability_results)
cs_threshold = 0.7
# Find the lowest proportion where mean_corr is still > 0.7
safe_drop = stability_df[stability_df['mean_corr'] >= cs_threshold]
cs_coeff = 1 - safe_drop['proportion_kept'].min() if not safe_drop.empty else 0

print(f"\nCalculated CS-coefficient (Strength): {cs_coeff:.3f}")

