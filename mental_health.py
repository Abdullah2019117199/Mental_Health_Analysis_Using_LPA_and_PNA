import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.covariance import GraphicalLassoCV
from sklearn.preprocessing import StandardScaler
from scipy.stats import spearmanr

# 1. SETUP FUNCTIONS
def estimate_strength(data):
    """Estimates the strength centrality of a network using Glasso"""
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(data)

    # Estimate partial correlations using GraphicalLasso
    model = GraphicalLassoCV(cv=5)
    model.fit(X_scaled)
    precision = model.precision_

    # Convert to partial correlation matrix
    d = np.sqrt(np.diag(precision))
    pcorr = -precision / np.outer(d, d)
    np.fill_diagonal(pcorr, 1)

    # Node Strength: Sum of absolute values of connections
    return np.sum(np.abs(pcorr), axis=1) - 1

# 2. DATA PREPARATION
