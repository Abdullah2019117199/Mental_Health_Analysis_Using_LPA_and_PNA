import pandas as pd
import numpy as np
from scipy.stats import chi2_contingency

def calculate_cramers_v(chi2_stat, n, min_dim):
    """Calculate Cramér's V statistic."""
    if min_dim == 0:
        return 0.0
    # Use max(0, min_dim) to avoid issues if dimension is 1
    return np.sqrt(chi2_stat / (n * max(1, min_dim)))

def run_chi_square_for_all_columns(df, target_col_name, alpha=0.05):
    """
    Runs Chi-Square tests for ALL other columns in the DataFrame against a single
    target variable and returns results in a pandas DataFrame.
    """
    # Automatically get all columns to test (exclude the target column itself)
    list_of_vars_to_test = [col for col in df.columns if col != target_col_name]

    results_list = []

    for test_var in list_of_vars_to_test:
        # Create contingency table
        contingency_table = pd.crosstab(df[test_var], df[target_col_name])
        n = contingency_table.sum().sum()

        # Check for sufficient categories (chi2 requires at least 2x2 table logic)
        if min(contingency_table.shape) < 2:
            print(f"Skipping '{test_var}' vs '{target_col_name}' due to insufficient categories (need at least 2 categories in both variables).")
            continue

        # Calculate stats
        chi2_stat, p_value, dof, expected_counts = chi2_contingency(contingency_table)

        # Determine significance
        significance = "Significant" if p_value < alpha else "Non-Significant"

        # Calculate Cramer's V (strength of association)
        cramers_v = calculate_cramers_v(chi2_stat, n, min(contingency_table.shape)-1)

        # Identify highest/lowest percentages for each column in the target variable
        col_percent_df = pd.crosstab(df[test_var], df[target_col_name], normalize='columns') * 100

        highest_pct_info = {}
        lowest_pct_info = {}
        for column in col_percent_df.columns:
            highest_idx = col_percent_df[column].idxmax()
            highest_val = col_percent_df[column].max()
            lowest_idx = col_percent_df[column].idxmin()
            lowest_val = col_percent_df[column].min()

            highest_pct_info[column] = f"'{highest_idx}' ({highest_val:.1f}%)"
            lowest_pct_info[column] = f"'{lowest_idx}' ({lowest_val:.1f}%)"

        # Append all results as a single row to our list
        results_list.append({
            'Variable Tested': test_var,
            'P-value': round(p_value, 5),
            'Significance Decision (alpha=0.05)': significance,
            'Cramers V (Association Strength)': round(cramers_v, 4),
            f'Highest %s in {target_col_name} Columns' % target_col_name: str(highest_pct_info),
            f'Lowest %s in {target_col_name} Columns' % target_col_name: str(lowest_pct_info)
        })

    # Convert the list of results into a clean pandas DataFrame
    results_df = pd.DataFrame(results_list)
    return results_df.sort_values(by='P-value')




